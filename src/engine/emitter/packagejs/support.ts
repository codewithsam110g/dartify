import { dartString } from "./text";

/**
 * Shared runtime support for multi-library runs (`E-40`).
 *
 * Declared once per output tree instead of once per library, so a `Promise`
 * returned by one generated library is the same Dart type another accepts.
 * Every library that uses a support name imports it and re-exports it (with
 * the `toFuture` extension), so users never need to import this file
 * directly; barrels see a single origin and nothing becomes ambiguous.
 */
export const SUPPORT_FILE_NAME = "dartify_support.dart";

/** Names a library re-exports when it uses `name` from the support library. */
export function supportExports(name: string): string[] {
  return name === "Promise" ? ["Promise", "PromiseToFuture"] : [name];
}

export const SUPPORT_PUBLIC_NAMES = ["JSBigInt", "Promise", "PromiseToFuture"];

export function renderSupportLibrary(): string {
  return [
    "// Generated by dart_bindgen: interop support shared by the generated libraries",
    "// Do not edit directly",
    "",
    "@JS()",
    "library dartify_support;",
    "",
    "import 'package:js/js.dart';",
    "import 'package:js/js_util.dart' show promiseToFuture;",
    "",
    "/// A JavaScript `bigint`. Dart's `BigInt` is a different runtime type.",
    "typedef JSBigInt = Object;",
    "",
    "/// A JavaScript `Promise`. Use `toFuture()` to await it from Dart.",
    `@JS(${dartString("Promise")})`,
    "abstract class Promise<T> {}",
    "",
    "extension PromiseToFuture<T> on Promise<T> {",
    "  Future<T> toFuture() => promiseToFuture<T>(this);",
    "}",
    "",
  ].join("\n");
}
