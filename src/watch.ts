interface FileState {
  /** Post-semantic, linked symbol groups declared by this file. */
  groups: Map<string, Symbol[]>;
  semantic: SemanticPassResult;
  namespaceAliases?: Set<string>;
  moduleExports: ModuleExportRecord[];
  generation: GenerationDiagnostic[];
  edges: Map<string, LinkEdge[]>;
  linkDiagnostics: LinkDiagnostic[];
  /** Files this file imports or references. */
  dependencies: Set<string>;
  /** A script file's declarations are global. */
  isScript: boolean;
  /** See `fingerprints`; keyed by FQN. */
  interfaceKey: Map<string, string>;
  memberKey: Map<string, string>;
  /** `extends`/`implements` per class or interface FQN. */
  heritageKey: Map<string, string>;
  /** Names and kinds only, per FQN; decides whether a replayed key is reusable. */
  lightKey: Map<string, string>;
  /** Minted aliases and redirects of the file; see `fingerprints`. */
  fileKey: string;
  /** Identifier tokens of the file text, to test whether a change concerns it. */
  tokens: Set<string>;
}

export interface WatchTimings {
  resolve: number;
  generate: number;
  link: number;
  render: number;
  write: number;
  total: number;
}

export interface WatchBuild {
  analysis: AnalysisReport;
  /** The linked program this build rendered (read-only; owned by the session). */
  program: LinkedProgram;
  files: Map<string, RenderedFile>;
  /** Source files regenerated by this build. */
  rebuilt: string[];
  /** Output files written (content changed) or removed by this build. */
  written: string[];
  removed: string[];
  timings: WatchTimings;
}

export interface WatchSessionOptions extends TranspilerOptions {
  /** Write changed outputs to `outDir` (default true). */
  write?: boolean;
}

function toForwardSlash(path: string): string {
  return path.split("\\").join("/");
}

export class WatchSession {
  private readonly run: ResolutionRun;
  private readonly files: string[];
  private readonly outDir: string;
  private readonly write: boolean;
  private readonly inputRoot: string | undefined;
  private readonly backend: Backend;
  private readonly states = new Map<string, FileState>();
  private readonly renderCache = new Map<string, unknown>();
  private readonly lastWritten = new Map<string, string>();
  private wasMultiLibrary: boolean | undefined;
  private liveFiles: Set<string> | undefined;
  private readonly statementCaches = new Map<string, StatementCache>();
  private built = false;

  constructor(options: WatchSessionOptions) {
    if (!Array.isArray(options.files) || options.files.length === 0) {
      throw new TranspileException("Files array cannot be empty", "INVALID_FILES");
    }
    this.files = [...new Set(options.files)].sort();
    this.outDir = options.outDir || "./dart_out";
    this.write = options.write ?? true;
    this.inputRoot = options.inputRoot ? resolve(options.inputRoot) : undefined;
    this.backend = createPackageJsBackend(options.jsRoot ? { jsRoot: options.jsRoot } : {});
    this.run = new ResolutionRun(this.files, options.tsConfigFilePath);
  }

  /**
   * Builds, reusing every cached file the change set cannot affect. The first
   * call is a full build. `changed` lists files modified, added or deleted
   * since the previous build; omit it to rebuild everything.
   */
  public async build(changed?: Iterable<string>): Promise<WatchBuild> {
    const started = performance.now();
    let mark = started;
    const lap = () => {
      const now = performance.now();
      const elapsed = now - mark;
      mark = now;
      return Math.round(elapsed * 10) / 10;
    };

    // Resolution: refresh changed files in the long-lived project.
    const changedFiles = changed
      ? new Set([...changed].map((file) => toForwardSlash(resolve(file))))
      : undefined;
    if (changedFiles && this.built) {
      for (const file of changedFiles) {
        this.run.project.getSourceFile(file)?.refreshFromFileSystemSync();
      }
    }
    this.run.resolveAndCategorize();
    const programFiles = [...this.run.inputFiles, ...this.run.packageDepFiles];
    const live = new Set(programFiles.map(([file]) => file));
    const fileSetChanged =
      this.liveFiles === undefined ||
      this.liveFiles.size !== live.size ||
      [...live].some((file) => !this.liveFiles!.has(file));
    this.liveFiles = live;
    const seeds = this.seedFiles(changedFiles, live);
    const unchanged = fileSetChanged
      ? undefined
      : new Set([...live].filter((file) => !seeds.has(file)));
    const resolution = this.run.buildResolutionReport(unchanged);
    const resolveTime = lap();

    // Generation + per-file semantic analysis. Seeds regenerate (replaying
    // their unchanged statements); a file whose *interface* changed
    // regenerates its importers too, and so on transitively. A file whose
    // members changed only forces its heritage dependents to re-render.
    for (const file of [...this.states.keys()]) if (!live.has(file)) this.states.delete(file);
    for (const file of [...this.statementCaches.keys()]) if (!live.has(file)) this.statementCaches.delete(file);
    const sources = new Map(programFiles);
    const dependents = new Map<string, Set<string>>();
    for (const [file, state] of this.states) {
      for (const dependency of state.dependencies) {
        const set = dependents.get(dependency) ?? new Set<string>();
        set.add(file);
        dependents.set(dependency, set);
      }
    }
    const scriptChanged = [...seeds].some(
      (file) => this.states.get(file)?.isScript && this.built,
    );
    const dirty = new Set<string>();
    const memberChanged = new Set<string>();
    let heritageChanged = false;
    const queue = scriptChanged ? [...live] : [...seeds];
    while (queue.length > 0) {
      const file = queue.shift()!;
      if (dirty.has(file)) continue;
      const sourceFile = sources.get(file);
      if (!sourceFile) continue;
      dirty.add(file);
      // Only a file's own edits are safe to replay statement by statement; a
      // file regenerated because an import changed may bind names differently.
      if (!seeds.has(file) || scriptChanged) this.statementCaches.delete(file);
      let statementCache = this.statementCaches.get(file);
      if (!statementCache) this.statementCaches.set(file, (statementCache = new Map()));
      const previous = this.states.get(file);
      const next = await this.regenerate(file, sourceFile, statementCache);
      this.states.set(file, next);
      const changedSurface = previous
        ? changedKeys(previous.interfaceKey, next.interfaceKey)
        : [...next.interfaceKey.keys()];
      const changedMembers = previous
        ? changedKeys(previous.memberKey, next.memberKey)
        : [...next.memberKey.keys()];
      changedMembers.forEach((fqn) => memberChanged.add(fqn));
      // Structural conformance relates classes to shape interfaces anywhere in
      // the program, so a changed shape re-renders every library.
      const shapeFQNs = new Set([...shapesOf(previous), ...shapesOf(next)]);
      if ([...changedMembers, ...changedSurface].some((fqn) => shapeFQNs.has(fqn))) {
        heritageChanged = true;
      }
      // Override correction walks heritage chains through files an importer
      // never names, so any heritage change re-renders every library.
      if (previous && changedKeys(previous.heritageKey, next.heritageKey).length > 0) {
        heritageChanged = true;
      }
      if (changedSurface.length > 0 || next.isScript) {
        // An importer can only observe a changed declaration it names.
        const names = namesOf(changedSurface);
        for (const dependent of dependents.get(file) ?? []) {
          if (dirty.has(dependent)) continue;
          const tokens = this.states.get(dependent)?.tokens;
          if (!tokens || [...names].some((name) => tokens.has(name))) queue.push(dependent);
        }
        if (next.isScript && this.built) {
          for (const other of live) if (!dirty.has(other)) queue.push(other);
        }
      }
    }
    const generateTime = lap();

    // Link dirty files against the whole merged table.
    const table = new Map<string, Symbol[]>();
    const namespaceExports = new Map<string, Set<string>>();
    const moduleExportTable: ModuleExportTable = new Map();
    for (const [file, state] of this.states) {
      for (const [fqn, group] of state.groups) table.set(fqn, group);
      if (state.namespaceAliases) namespaceExports.set(file, state.namespaceAliases);
      if (state.moduleExports.length > 0) moduleExportTable.set(file, state.moduleExports);
    }
    const dirtyGroups = new Map<string, Symbol[]>();
    for (const file of dirty) {
      for (const [fqn, group] of this.states.get(file)?.groups ?? []) dirtyGroups.set(fqn, group);
    }
    // Semantic redirects (an interface merged into its constructor companion,
    // canonicalized anonymous shapes) can be referenced from other files; the
    // whole-program pass rewrites those references, so apply every file's
    // redirects to the files being re-linked.
    const redirects = new Map<string, string>();
    for (const state of this.states.values()) {
      for (const redirect of state.semantic.report.redirects) {
        redirects.set(redirect.fromFQN, redirect.toFQN);
      }
    }
    rewriteRedirects(dirtyGroups, redirects);
    const linked = linkReferences(dirtyGroups, table, namespaceExports);
    for (const file of dirty) {
      const state = this.states.get(file);
      if (!state) continue;
      state.edges = new Map();
      state.linkDiagnostics = [];
    }
    for (const [fqn, edges] of linked.edgesByFQN) {
      this.states.get(sourceFileOfFQN(fqn))?.edges.set(fqn, edges);
    }
    for (const diagnostic of linked.diagnostics) {
      this.states.get(sourceFileOfFQN(diagnostic.ownerFQN))?.linkDiagnostics.push(diagnostic);
    }
    const allEdges = new Map<string, LinkEdge[]>();
    const linkDiagnostics: LinkDiagnostic[] = [];
    const generation: GenerationDiagnostic[] = [];
    for (const state of this.states.values()) {
      for (const [fqn, edges] of state.edges) allEdges.set(fqn, edges);
      linkDiagnostics.push(...state.linkDiagnostics);
    }
    // In a cold run's file order (inputs, then dependencies, each sorted), not
    // the order the states were first built in, so both report one list.
    for (const [file] of programFiles) generation.push(...(this.states.get(file)?.generation ?? []));
    linkDiagnostics.sort((a, b) =>
      `${a.ownerFQN}\u0000${a.writtenName}`.localeCompare(`${b.ownerFQN}\u0000${b.writtenName}`),
    );
    const semantic = mergeSemanticResults([...this.states.values()].map((state) => state.semantic));
    const report = summarizeLinks(allEdges, linkDiagnostics, table.keys(), semantic);
    const moduleExports = linkModuleExports(moduleExportTable, table, [...this.run.inputFiles.keys()].sort());
    report.moduleExportDiagnostics = [...moduleExports.diagnostics];
    const program: LinkedProgram = { symbols: table, namespaceExports, moduleExports, report };
    const linkTime = lap();

    // Render only affected libraries; a change between one and several
    // libraries moves shared support, so it re-renders everything.
    const inputRoot = this.inputRoot ?? resolvedInputRoot(resolution.inputFiles);
    const multiLibrary = this.states.size > 1;
    const renderDirty =
      this.wasMultiLibrary === undefined || this.wasMultiLibrary !== multiLibrary || heritageChanged
        ? new Set(live)
        : new Set([...dirty, ...heritageDependents(table, memberChanged)]);
    this.wasMultiLibrary = multiLibrary;
    const files = renderAllFiles(program, this.outDir, inputRoot, false, this.backend, {
      dirty: renderDirty,
      cache: this.renderCache,
    });
    const renderTime = lap();

    // Write only what changed; remove outputs that no longer exist.
    const written: string[] = [];
    const removed: string[] = [];
    if (this.write && generation.length === 0) {
      for (const [outputPath, file] of files) {
        if (this.lastWritten.get(outputPath) === file.content) continue;
        await mkdir(dirname(outputPath), { recursive: true });
        await writeFile(outputPath, file.content, "utf-8");
        this.lastWritten.set(outputPath, file.content);
        written.push(outputPath);
      }
      for (const outputPath of [...this.lastWritten.keys()]) {
        if (files.has(outputPath)) continue;
        await rm(outputPath, { force: true });
        this.lastWritten.delete(outputPath);
        removed.push(outputPath);
      }
    }
    const writeTime = lap();
    this.built = true;

    return {
      analysis: { resolution, generation, link: report },
      program,
      files,
      rebuilt: [...dirty].sort(),
      written: written.sort(),
      removed: removed.sort(),
      timings: {
        resolve: resolveTime,
        generate: generateTime,
        link: linkTime,
        render: renderTime,
        write: writeTime,
        total: Math.round((performance.now() - started) * 10) / 10,
      },
    };
  }

  /** Files to regenerate first: changed or new files; everything on the first build. */
  private seedFiles(changed: Set<string> | undefined, live: Set<string>): Set<string> {
    if (!changed || !this.built) return new Set(live);
    const seeds = new Set<string>();
    for (const file of live) if (!this.states.has(file) || changed.has(file)) seeds.add(file);
    // A deleted file's importers must re-bind.
    for (const file of changed) {
      if (live.has(file) || !this.states.has(file)) continue;
      for (const [other, state] of this.states) {
        if (live.has(other) && state.dependencies.has(file)) seeds.add(other);
      }
    }
    return seeds;
  }

  private async regenerate(
    file: string,
    sourceFile: import("ts-morph").SourceFile,
    statementCache: StatementCache,
  ): Promise<FileState> {
    const table = new SymbolTable();
    const namespaceExports = new Map<string, Set<string>>();
    const moduleExports: ModuleExportTable = new Map();
    const freshFQNs = new Set<string>();
    const generation = [
      ...syntacticDiagnosticsOf(sourceFile),
      ...(await generateSymbols(file, sourceFile, table, namespaceExports, moduleExports, {
        statementCache,
        freshFQNs,
      })),
    ];
    const groups = table.release();
    const semantic = runSemanticPassOnDraft(groups, moduleExports);
    const keys = fingerprints(groups, semantic, this.states.get(file), freshFQNs);
    return {
      groups,
      semantic,
      ...(namespaceExports.get(file) ? { namespaceAliases: namespaceExports.get(file)! } : {}),
      moduleExports: moduleExports.get(file) ?? [],
      generation,
      edges: new Map(),
      linkDiagnostics: [],
      dependencies: new Set(
        sourceFile
          .getReferencedSourceFiles()
          .map((referenced) => toForwardSlash(referenced.getFilePath())),
      ),
      isScript: !isModule(sourceFile),
      interfaceKey: keys.interfaceKey,
      memberKey: keys.memberKey,
      heritageKey: keys.heritageKey,
      lightKey: keys.lightKey,
      fileKey: keys.fileKey,
      tokens: new Set(sourceFile.getFullText().match(/[A-Za-z_$][\w$]*/g) ?? []),
    };
  }
}

/** Fields that never affect another file's generation or rendering. */
function stripVolatile(key: string, value: unknown): unknown {
  return key === "loc" || key === "jsDoc" || key === "resolvedFQN" || key === "resolvedDartName"
    ? undefined
    : value;
}

/**
 * Two fingerprints of a file's post-semantic symbols.
 *
 * `interfaceKey` covers what *importers* can observe while generating, linking
 * or rendering: names, kinds, type parameters, heritage, member counts (which
 * decide callable-interface typedefs), redirects, and the full IR of values,
 * enums, functions and aliases (checker results such as `typeof x` read
 * them). `memberKey` adds class and interface members, which only heritage
 * dependents read (inherited members, property-bag fields, overrides).
 */
function fingerprints(
  groups: ReadonlyMap<string, readonly Symbol[]>,
  semantic: SemanticPassResult,
  previous?: FileState,
  fresh?: ReadonlySet<string>,
): {
  interfaceKey: Map<string, string>;
  memberKey: Map<string, string>;
  heritageKey: Map<string, string>;
  lightKey: Map<string, string>;
  fileKey: string;
} {
  const interfaceKey = new Map<string, string>();
  const memberKey = new Map<string, string>();
  const heritageKey = new Map<string, string>();
  const lightKey = new Map<string, string>();
  // File-level rewrites that can reach declarations whose statements were
  // replayed: minted alias names (allocated over the file's set of texts) and
  // anonymous-shape redirects. If either changed, nothing is reused.
  const fileKey = JSON.stringify([
    [...groups.keys()].filter((fqn) => groups.get(fqn)!.some((symbol) => symbol.minted)),
    semantic.report.redirects,
  ]);
  const reusable = previous !== undefined && fresh !== undefined && previous.fileKey === fileKey;
  for (const fqn of [...groups.keys()].sort()) {
    const light = JSON.stringify(
      groups.get(fqn)!.map((symbol) =>
        symbol.facets.map((facet) => [facet.ir.kind, facet.ir.dartName, facet.ir.jsName, facet.emit, facet.namespace]),
      ),
    );
    lightKey.set(fqn, light);
    if (reusable && !fresh!.has(fqn) && previous!.lightKey.get(fqn) === light && previous!.memberKey.has(fqn)) {
      interfaceKey.set(fqn, previous!.interfaceKey.get(fqn)!);
      memberKey.set(fqn, previous!.memberKey.get(fqn)!);
      const heritage = previous!.heritageKey.get(fqn);
      if (heritage !== undefined) heritageKey.set(fqn, heritage);
      continue;
    }
    const surface: unknown[] = [];
    for (const symbol of groups.get(fqn)!) {
      for (const facet of symbol.facets) {
        const ir = facet.ir as unknown as Record<string, unknown>;
        const common = {
          fqn,
          kind: ir.kind,
          namespace: facet.namespace,
          emit: facet.emit,
          synthetic: facet.synthetic,
          dartName: ir.dartName,
          jsName: ir.jsName,
          typeParams: ir.typeParams,
          scopes: facet.origin.scopes,
          fileIsModule: facet.origin.fileIsModule,
        };
        if (ir.kind === "class" || ir.kind === "interface") {
          heritageKey.set(fqn, JSON.stringify([ir.extends, ir.implements], stripVolatile));
          surface.push({
            ...common,
            isAbstract: ir.isAbstract,
            extends: ir.extends,
            implements: ir.implements,
            // Only what the callable-interface/typedef decision reads.
            shape: ["callSignatures", "constructSignatures", "indexSignatures", "constructors"].map(
              (list) => ((ir[list] as unknown[] | undefined)?.length ?? 0) > 0,
            ).concat(
              ["properties", "methods", "getAccessors", "setAccessors"].some(
                (list) => ((ir[list] as unknown[] | undefined)?.length ?? 0) > 0,
              ),
            ),
          });
        } else {
          surface.push({ ...common, ir });
        }
      }
    }
    interfaceKey.set(fqn, JSON.stringify(surface, stripVolatile));
    memberKey.set(
      fqn,
      JSON.stringify(groups.get(fqn)!.map((symbol) => symbol.facets.map((facet) => facet.ir)), stripVolatile),
    );
  }
  for (const redirect of semantic.report.redirects) {
    interfaceKey.set(`redirect:${redirect.fromFQN}`, redirect.toFQN);
  }
  return { interfaceKey, memberKey, heritageKey, lightKey, fileKey };
}

function shapesOf(state: FileState | undefined): string[] {
  if (!state) return [];
  const result: string[] = [];
  for (const [fqn, group] of state.groups) {
    if (group.some((symbol) => symbol.facets.some(isShapeCandidate))) result.push(fqn);
  }
  return result;
}

/** FQNs whose fingerprint differs between two maps (added, removed or changed). */
function changedKeys(before: ReadonlyMap<string, string>, after: ReadonlyMap<string, string>): string[] {
  const changed: string[] = [];
  for (const [key, value] of after) if (before.get(key) !== value) changed.push(key);
  for (const key of before.keys()) if (!after.has(key)) changed.push(key);
  return changed;
}

/** The identifier tokens a changed FQN can be referred to by. */
function namesOf(fqns: readonly string[]): Set<string> {
  const names = new Set<string>();
  for (const raw of fqns) {
    for (const fqn of raw.replace(/^redirect:/, "").split(" ")) {
      const logical = fqn.slice(fqn.indexOf("::") + 2);
      for (const segment of logical.split("|")) names.add(segment.replace(/['"]/g, ""));
    }
  }
  return names;
}

/**
 * Files declaring a class or interface that (transitively) inherits from one
 * of the `changed` declarations; rendering them reads the inherited members.
 */
function heritageDependents(
  table: ReadonlyMap<string, readonly Symbol[]>,
  changed: ReadonlySet<string>,
): Set<string> {
  if (changed.size === 0) return new Set();
  const children = new Map<string, string[]>();
  for (const [fqn, group] of table) {
    for (const symbol of group) {
      for (const facet of symbol.facets) {
        const ir = facet.ir as unknown as {
          kind: string;
          extends?: { reference?: { resolvedFQN?: string } } | { reference?: { resolvedFQN?: string } }[];
          implements?: { reference?: { resolvedFQN?: string } }[];
        };
        if (ir.kind !== "class" && ir.kind !== "interface") continue;
        const parents = [
          ...(Array.isArray(ir.extends) ? ir.extends : ir.extends ? [ir.extends] : []),
          ...(ir.implements ?? []),
        ];
        for (const parent of parents) {
          const target = parent.reference?.resolvedFQN;
          if (!target) continue;
          const list = children.get(target) ?? [];
          list.push(fqn);
          children.set(target, list);
        }
      }
    }
  }
  const result = new Set<string>();
  const queue = [...changed];
  const seen = new Set(queue);
  while (queue.length > 0) {
    const fqn = queue.pop()!;
    for (const child of children.get(fqn) ?? []) {
      if (seen.has(child)) continue;
      seen.add(child);
      result.add(sourceFileOfFQN(child));
      queue.push(child);
    }
  }
  return result;
}

function isModule(sourceFile: { compilerNode: unknown }): boolean {
  const node = sourceFile.compilerNode as { externalModuleIndicator?: unknown };
  return node.externalModuleIndicator !== undefined;
}

